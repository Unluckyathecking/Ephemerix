import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "deploy"))

from lock_requirements import export_requirements, pinned_lines


def test_pinned_lines_accepts_exact_pins_and_markers() -> None:
    text = ("# autogenerated\nnumpy==2.4.0\n    # via scipy\n"
            "numcodecs==0.17.1 ; python_full_version >= '3.12'\nuvicorn[standard]==0.54.0\n")
    assert pinned_lines(text) == ["numpy==2.4.0",
                                  "numcodecs==0.17.1 ; python_full_version >= '3.12'",
                                  "uvicorn[standard]==0.54.0"]


@pytest.mark.parametrize("bad", ["numpy", "numpy>=2", "numpy~=2.0", "-e .", "pkg @ https://x/y"])
def test_unpinned_lines_are_rejected(bad: str) -> None:
    with pytest.raises(ValueError):
        pinned_lines(f"ok==1.0\n{bad}\n")


def test_empty_export_is_rejected() -> None:
    with pytest.raises(ValueError):
        pinned_lines("# nothing\n")


def test_exported_lock_is_all_exact_pins(tmp_path: Path) -> None:
    out = export_requirements(ROOT, tmp_path / "req.txt")  # offline: reads uv.lock only
    lines = out.read_text().splitlines()
    assert len(lines) > 20 and all("==" in line for line in lines)
    assert any(line.startswith("fastapi==") for line in lines)
